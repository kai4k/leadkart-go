var updateRouteGates = flag.Bool("update-route-gates", false, "rewrite the generated route -> gate table in docs/BFF_API_CHANGES.md")

const (
	routeGatesBegin = "<!-- route-gates:begin (generated by TestArch_BFFRouteGateTable; do not edit by hand) -->"
	routeGatesEnd   = "<!-- route-gates:end -->"
)

// gateUse is one authn wrapper on a route.
type gateUse struct {
	factory string
	perms   []string // resolved permission names (RequirePermission and friends)
	pathVar string   // the path value a self / path-tenant gate names
}

// routeGateRow is one rendered route.
type routeGateRow struct{ pattern, authz, scope string }

// permissionFactories are the authn factories whose arguments after the verifier and
// the stamp validator are permission names (a string literal is a path value name).
var permissionFactories = map[string]bool{
	"RequirePermission": true, "RequireAnyPermission": true, "RequirePermissionOrSelf": true,
	"RequireTenantPermission": true, "RequirePlatformGate": true,
}

// authnHandlerFactories are every authn wrapper a route may use, and what each is.
var authnHandlerFactories = map[string]bool{
	"RequireFreshStamp": true, "RequireAuth": true, "RequirePlatform": true,
	"RejectTenantScope": true, "TenantScopeLifecycle": true, "TenantScopePathOnly": true,
	"TenantScopeMatchesPath": true, "TenantScopeWritable": true, "HonourTenantScope": true,
	"DenySelfPerson": true, "DenySelfTarget": true,
}

type defAt struct {
	pos  token.Pos
	expr ast.Expr
}

type gateReader struct {
	fset  *token.FileSet
	defs  map[string][]defAt // local variable -> every `name := expr` in AddRoutes
	errs  []string
	roots map[string]reflect.Value // permission catalogue roots by "pkg.Name"
}

func (g *gateReader) fail(n ast.Node, format string, args ...any) {
	g.errs = append(g.errs, fmt.Sprintf("%s: %s", g.fset.Position(n.Pos()), fmt.Sprintf(format, args...)))
}

// lookup returns the expression a local variable named id was bound to, as of use.
func (g *gateReader) lookup(id *ast.Ident) (ast.Expr, bool) {
	var found ast.Expr
	for _, d := range g.defs[id.Name] {
		if d.pos < id.Pos() {
			found = d.expr
		}
	}
	return found, found != nil
}

// authnSel reports whether e is `authn.<Name>` and returns Name.
func authnSel(e ast.Expr) (string, bool) {
	sel, ok := ast.Unparen(e).(*ast.SelectorExpr)
	if !ok {
		return "", false
	}
	if id, ok := sel.X.(*ast.Ident); ok && id.Name == "authn" {
		return sel.Sel.Name, true
	}
	return "", false
}

// permName resolves a permission argument (p.Users.View, permission.IdentityPermissions.Users.View).
func (g *gateReader) permName(e ast.Expr) (string, bool) {
	var path []string
	cur := ast.Unparen(e)
	for {
		sel, ok := cur.(*ast.SelectorExpr)
		if !ok {
			break
		}
		path = append([]string{sel.Sel.Name}, path...)
		cur = ast.Unparen(sel.X)
	}
	id, ok := cur.(*ast.Ident)
	if !ok || len(path) == 0 {
		return "", false
	}
	// `p.Users.View` with p := permission.IdentityPermissions -> root + path.
	if def, ok := g.lookup(id); ok {
		sel, isSel := ast.Unparen(def).(*ast.SelectorExpr)
		if !isSel {
			return "", false
		}
		pk, ok := sel.X.(*ast.Ident)
		if !ok {
			return "", false
		}
		path = append([]string{sel.Sel.Name}, path...)
		id = pk
	}
	// else: `permission.IdentityPermissions.Users.View`: id is the package, path[0] the var.
	rootName := id.Name + "." + path[0]
	root, ok := g.roots[rootName]
	if !ok {
		return "", false
	}
	v := root
	for _, f := range path[1:] {
		v = v.FieldByName(f)
		if !v.IsValid() {
			return "", false
		}
	}
	if v.Kind() != reflect.String {
		return "", false
	}
	return v.String(), true
}

// factoryGate describes `authn.<Factory>(args...)` (the factory form).
func (g *gateReader) factoryGate(call *ast.CallExpr, name string, extra []ast.Expr) gateUse {
	use := gateUse{factory: name}
	args := append(append([]ast.Expr{}, call.Args...), extra...)
	if permissionFactories[name] {
		for i, a := range args {
			if i < 2 { // verifier, stampValidator
				continue
			}
			if lit, ok := a.(*ast.BasicLit); ok && lit.Kind == token.STRING {
				use.pathVar, _ = strconv.Unquote(lit.Value)
				continue
			}
			p, ok := g.permName(a)
			if !ok {
				g.fail(a, "cannot resolve the permission argument of authn.%s", name)
				continue
			}
			use.perms = append(use.perms, p)
		}
		return use
	}
	for _, a := range call.Args {
		if lit, ok := a.(*ast.BasicLit); ok && lit.Kind == token.STRING {
			use.pathVar, _ = strconv.Unquote(lit.Value)
		}
	}
	return use
}

// wrapperGates reads an expression that evaluates to a middleware (a function from
// handler to handler): `authn.F(args)`, a local variable bound to one, or such a
// variable called with more permission arguments (`platform(p.Tenants.Suspend)`).
func (g *gateReader) wrapperGates(e ast.Expr, extra []ast.Expr) []gateUse {
	switch x := ast.Unparen(e).(type) {
	case *ast.CallExpr:
		if name, ok := authnSel(x.Fun); ok {
			if !authnHandlerFactories[name] && !permissionFactories[name] {
				g.fail(x, "unknown authn wrapper authn.%s", name)
				return nil
			}
			return []gateUse{g.factoryGate(x, name, extra)}
		}
		if id, ok := ast.Unparen(x.Fun).(*ast.Ident); ok {
			return g.wrapperGates(id, append(append([]ast.Expr{}, x.Args...), extra...))
		}
		g.fail(x, "cannot read the wrapper expression")
	case *ast.Ident:
		def, ok := g.lookup(x)
		if !ok {
			g.fail(x, "wrapper variable %q has no definition in AddRoutes", x.Name)
			return nil
		}
		return g.wrapperGates(def, extra)
	case *ast.SelectorExpr:
		// `writable := authn.TenantScopeWritable`: a handler wrapper bound to a variable.
		if name, ok := authnSel(x); ok && authnHandlerFactories[name] {
			return []gateUse{{factory: name}}
		}
		g.fail(x, "cannot read the wrapper expression")
	default:
		g.fail(e, "cannot read the wrapper expression")
	}
	return nil
}

// routeGates reads the handler argument of a registration, outermost wrapper first.
func (g *gateReader) routeGates(e ast.Expr) []gateUse {
	call, ok := ast.Unparen(e).(*ast.CallExpr)
	if !ok || len(call.Args) == 0 {
		return nil
	}
	last := call.Args[len(call.Args)-1]
	switch fun := ast.Unparen(call.Fun).(type) {
	case *ast.SelectorExpr:
		// authn.X(handler): a direct handler wrapper (RejectTenantScope(h)); any other
		// selector call is the handler constructor and ends the walk.
		if name, ok := authnSel(fun); ok {
			if !authnHandlerFactories[name] {
				g.fail(call, "unknown authn wrapper authn.%s", name)
				return nil
			}
			return append([]gateUse{{factory: name}}, g.routeGates(last)...)
		}
		return nil
	case *ast.CallExpr:
		return append(g.wrapperGates(fun, nil), g.routeGates(last)...)
	case *ast.Ident:
		if _, isVar := g.lookup(fun); isVar {
			return append(g.wrapperGates(fun, nil), g.routeGates(last)...)
		}
		return nil // handleX(log, a): the handler constructor
	default:
		g.fail(call, "cannot read the wrapper of this route")
	}
	return nil
}

const scopePathTenant = "path tenant (the URL names the tenant; a header that differs is 400 `tenant_scope_conflict`)"

// renderGates turns a route's wrappers into the two table cells.
func renderGates(gates []gateUse) (authz, scope string) {
	var parts []string
	scope = "default: reads honoured for an operator; a write is refused (403 `tenant_scope_read_only`)"
	bt := func(ss []string) string {
		q := make([]string, len(ss))
		for i, s := range ss {
			q[i] = "`" + s + "`"
		}
		return strings.Join(q, ", ")
	}
	signedIn := false
	for _, u := range gates {
		switch u.factory {
		case "RequireFreshStamp", "RequireAuth":
			signedIn = true
		case "RequirePermission":
			parts = append(parts, bt(u.perms))
		case "RequireAnyPermission":
			parts = append(parts, "any of "+bt(u.perms))
		case "RequirePermissionOrSelf":
			parts = append(parts, bt(u.perms)+", or the member's own record (`{"+u.pathVar+"}`)")
		case "RequireTenantPermission":
			parts = append(parts, bt(u.perms)+" in the path tenant")
			scope = scopePathTenant
		case "RequirePlatformGate":
			parts = append(parts, "platform operator and "+bt(u.perms))
		case "RequirePlatform":
			parts = append(parts, "platform operator")
		case "DenySelfPerson", "DenySelfTarget":
			parts = append(parts, "not on yourself")
		case "RejectTenantScope":
			scope = "not supported (403 `tenant_scope_not_supported`)"
		case "TenantScopeWritable":
			scope = "honoured; writes allowed"
		case "TenantScopeLifecycle", "TenantScopePathOnly", "TenantScopeMatchesPath":
			scope = scopePathTenant
		case "HonourTenantScope":
			scope = "honoured"
		}
	}
	switch {
	case len(parts) > 0:
		authz = strings.Join(parts, "; ")
	case signedIn:
		authz = "signed in (any member)"
	default:
		authz = "public (no token)"
		scope = "n/a"
	}
	return authz, scope
}

func (g *gateReader) collectDefs(body *ast.BlockStmt) {
	ast.Inspect(body, func(n ast.Node) bool {
		as, ok := n.(*ast.AssignStmt)
		if !ok || as.Tok != token.DEFINE || len(as.Lhs) != len(as.Rhs) {
			return true
		}
		for i, l := range as.Lhs {
			if id, ok := l.(*ast.Ident); ok {
				g.defs[id.Name] = append(g.defs[id.Name], defAt{pos: id.Pos(), expr: as.Rhs[i]})
			}
		}
		return true
	})
}

// renderIdentityRouteGateTable parses ports.AddRoutes and returns the markdown table.
func renderIdentityRouteGateTable(t *testing.T) string {
	t.Helper()
	file := filepath.Join(internalDir(t), "identity", "ports", "http.go")
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.SkipObjectResolution)
	if err != nil {
		t.Fatalf("parse %s: %v", file, err)
	}
	g := &gateReader{
		fset: fset, defs: map[string][]defAt{},
		roots: map[string]reflect.Value{"permission.IdentityPermissions": reflect.ValueOf(permission.IdentityPermissions)},
	}
	var rows []routeGateRow
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Name.Name != "AddRoutes" || fd.Body == nil {
			continue
		}
		g.collectDefs(fd.Body)
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) != 2 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "Handle" {
				return true
			}
			if x, ok := sel.X.(*ast.Ident); !ok || x.Name != "mux" {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				g.fail(call, "route pattern is not a string literal")
				return true
			}
			pattern, _ := strconv.Unquote(lit.Value)
			authz, scope := renderGates(g.routeGates(call.Args[1]))
			rows = append(rows, routeGateRow{pattern: pattern, authz: authz, scope: scope})
			return true
		})
	}
	if len(g.errs) > 0 {
		t.Fatalf("the route gate generator could not read %d expression(s):\n  %s", len(g.errs), strings.Join(g.errs, "\n  "))
	}
	if len(rows) < 60 {
		t.Fatalf("the generator found only %d identity routes (AddRoutes registers more than 60): the scan lost its way", len(rows))
	}
	var b strings.Builder
	b.WriteString("| Route | Who may call it | `X-Tenant-Id` (operators) |\n|---|---|---|\n")
	for _, r := range rows {
		b.WriteString("| `" + r.pattern + "` | " + r.authz + " | " + r.scope + " |\n")
	}
	return b.String()
}

// arch-test:no-negative-fixture (RED proof: change a gate or a permission in ports.AddRoutes and this test fails against the committed table; the reader's fail-closed errors are exercised by TestMeta_RouteGateReaderFailsClosed)
func TestArch_BFFRouteGateTable(t *testing.T) {
	want := renderIdentityRouteGateTable(t)
	docPath := filepath.Join(repoRoot(t), "docs", "BFF_API_CHANGES.md")
	raw, err := os.ReadFile(docPath)
	if err != nil {
		t.Fatalf("read %s: %v", docPath, err)
	}
	doc := strings.ReplaceAll(string(raw), "\r\n", "\n")
	start := strings.Index(doc, routeGatesBegin)
	end := strings.Index(doc, routeGatesEnd)
	if start < 0 || end < start {
		t.Fatalf("%s lacks the generated block %q ... %q", docPath, routeGatesBegin, routeGatesEnd)
	}
	have := doc[start+len(routeGatesBegin)+1 : end]
	if *updateRouteGates {
		out := doc[:start+len(routeGatesBegin)+1] + want + doc[end:]
		if err := os.WriteFile(docPath, []byte(out), 0o644); err != nil { //nolint:gosec // G306: a documentation file in the repository.
			t.Fatalf("write %s: %v", docPath, err)
		}
		return
	}
	if have != want {
		t.Fatalf("the route -> gate table in docs/BFF_API_CHANGES.md is out of date with ports.AddRoutes.\nRegenerate: go test ./internal/architecture -run TestArch_BFFRouteGateTable -update-route-gates\nfirst difference: %s", firstDiff(have, want))
	}
}

func firstDiff(a, b string) string {
	al, bl := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := 0; i < len(al) || i < len(bl); i++ {
		var x, y string
		if i < len(al) {
			x = al[i]
		}
		if i < len(bl) {
			y = bl[i]
		}
		if x != y {
			return fmt.Sprintf("line %d:\n  doc:       %s\n  generated: %s", i+1, x, y)
		}
	}
	return "(none)"
}

// The reader fails closed: a permission it cannot resolve, a wrapper it does not know
// and a variable with no definition are errors, never a shorter table.
func TestMeta_RouteGateReaderFailsClosed(t *testing.T) {
	read := func(src string) []string {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, "x.go", "package x\n"+src, parser.SkipObjectResolution)
		if err != nil {
			t.Fatal(err)
		}
		g := &gateReader{fset: fset, defs: map[string][]defAt{},
			roots: map[string]reflect.Value{"permission.IdentityPermissions": reflect.ValueOf(permission.IdentityPermissions)}}
		fd := f.Decls[0].(*ast.FuncDecl)
		g.collectDefs(fd.Body)
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			if call, ok := n.(*ast.CallExpr); ok && len(call.Args) == 2 {
				if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Handle" {
					g.routeGates(call.Args[1])
				}
			}
			return true
		})
		return g.errs
	}
	if errs := read(`func AddRoutes() { p := permission.IdentityPermissions
		gate := authn.RequirePermission(v, s, p.Users.View)
		mux.Handle("GET /a", gate(h(log))) }`); len(errs) != 0 {
		t.Fatalf("a readable route reported errors: %v", errs)
	}
	for name, src := range map[string]string{
		"unknown permission": `func AddRoutes() { p := permission.IdentityPermissions
			mux.Handle("GET /a", authn.RequirePermission(v, s, p.Users.Nope)(h(log))) }`,
		"unknown wrapper":    `func AddRoutes() { mux.Handle("GET /a", authn.Mystery(v, s)(h(log))) }`,
		"unreadable factory": `func AddRoutes() { mux.Handle("GET /a", factories[0](h(log))) }`,
	} {
		if errs := read(src); len(errs) == 0 {
			t.Errorf("%s: the reader accepted an expression it cannot read", name)
		}
	}
}
