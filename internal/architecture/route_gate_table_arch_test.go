// route_gate_table_arch_test.go — the route -> gate table in docs/BFF_API_CHANGES.md
// is GENERATED from the identity route registrations, so it cannot drift from the
// code: this test renders it and compares it with the block between the markers.
//
// The identity routes are registered in one function (ports.AddRoutes) with a regular
// shape: `mux.Handle("METHOD /path", wrapper(wrapper(handler)))`, where a wrapper is
// either an authn factory call (`authn.RequirePermission(verifier, stampValidator,
// p.Users.View)`), a local variable bound once to one (`usersView`, `platform`), or a
// direct authn handler wrapper (`authn.RejectTenantScope(h)`). The generator reads the
// source with go/parser (no type-check), resolves a local variable to the expression it
// was bound to by position, and resolves a permission argument (`p.Users.View`, where
// `p := permission.IdentityPermissions`) against the real permission catalogue by
// reflection. It FAILS CLOSED: a wrapper, a variable or a permission expression it
// cannot read is an error naming the line, never a silently shorter table.
//
// Regenerate after a route change:
//
//	go test ./internal/architecture -run TestArch_BFFRouteGateTable -update-route-gates
package architecture_test

